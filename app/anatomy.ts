export function explanation(
 conceptId: string,
 system: SystemId,
 labels?: {tr: string; la: string},
): string {
 const custom = EXPLANATIONS[conceptId];
 if (custom) return custom;
 const sys = SYSTEMS.find(s => s.id === system);
 if (labels?.tr.trim()) {
  const la = labels.la.trim();
  const name = la ? `${labels.tr} (${la})` : labels.tr;
  if (sys?.description) return `${name}. ${sys.description}`;
  return `${name}.`;
 }
 return sys?.description ?? '';
}
