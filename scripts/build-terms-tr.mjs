function capitalize(s) {
  if (!s) return s;
  return s.charAt(0).toUpperCase() + s.slice(1);
}

function lowerFirstTr(s) {
  if (!s) return s;
  return s.toLocaleLowerCase('tr-TR').charAt(0) + s.slice(1);
}

function translatePhrase(enRaw) {
  let en = enRaw.trim();
  let low = en.toLowerCase();

  // Check exact match first
  if (EXACT_BASE.has(low)) {
    const [la, tr] = EXACT_BASE.get(low);
    return {la, tr};
  }

  // Handle "right ..." / "left ..." prefix
  for (const [sideEn, sideLa, sideLaFem, sideTr] of [
    ['right ', 'dexter', 'dextra', 'Sağ '],
    ['left ', 'sinister', 'sinistra', 'Sol '],
  ]) {
    if (low.startsWith(sideEn)) {
      const rest = en.slice(sideEn.length);
      const sub = translatePhrase(rest);
      const isFem = /^(Arteria|Vena|Costa|Cartilago|Scapula|Clavicula|Ulna|Tibia|Fibula|Patella|Maxilla|Mandibula|Concha|Glandula|Valva|Valvula|Cuspis|Fascia|Membrana|Pars|Facies|Regio|Zona|Cavitas|Camera|Fossa|Incisura|Linea|Stria|Lamina|Tunica|Plica|Taenia|Ala|Orbita|Auris|Naris|Tonsilla|Pleura|Pulmo)/i.test(sub.la);
      const adj = isFem ? sideLaFem : sideLa;
      return {
        la: `${sub.la} (${adj})`,
        tr: `${sideTr}${lowerFirstTr(sub.tr)}`,
      };
    }
  }

  // Handle ordinal prefixes: "first rib", "second metacarpal bone", etc.
  for (const [ordEn, roman, ordTr] of ORDINALS) {
    if (low.startsWith(ordEn + ' ')) {
      const rest = en.slice(ordEn.length + 1);
      const sub = translatePhrase(rest);
      return {
        la: `${sub.la} (${roman})`,
        tr: `${ordTr} ${lowerFirstTr(sub.tr)}`,
      };
    }
  }

  // Handle "X of right Y" / "X of left Y" only when not already starting with right/left
  const ofIdx = low.indexOf(' of ');
  if (ofIdx > 0) {
    const headStr = en.slice(0, ofIdx).trim();
    const tailStr = en.slice(ofIdx + 4).trim();
    const head = translatePhrase(headStr);
    const tail = translatePhrase(tailStr);
    return {
      la: `${head.la} (${tail.la})`,
      tr: `${tail.tr} ${lowerFirstTr(head.tr)}`,
    };
  }

  // Token-by-token translation for compound anatomical names (e.g., "anterior interventricular artery")
  const tokens = low.replace(/[()]/g, '').split(/[\s/-]+/).filter(Boolean);
  if (tokens.length > 0) {
    const headToken = tokens[tokens.length - 1];
    const modTokens = tokens.slice(0, -1);
    const headInfo = TOKEN_MAP[headToken];
    if (headInfo && ['artery', 'vein', 'nerve', 'muscle', 'bone', 'cartilage', 'ligament', 'tendon', 'membrane', 'fascia', 'ganglion', 'plexus', 'duct', 'canal', 'sinus', 'valve', 'lobe', 'segment', 'branch', 'tributary', 'trunk', 'cavity', 'chamber', 'wall', 'region', 'zone', 'part', 'layer', 'gyrus', 'sulcus', 'nucleus', 'tract', 'fossa', 'foramen', 'line', 'arch', 'ring', 'tree', 'system', 'organ', 'tissue', 'tooth'].includes(headToken)) {
      const laMods = modTokens.map(m => TOKEN_MAP[m]?.la ?? m).join(' ');
      const trMods = modTokens.map(m => TOKEN_MAP[m]?.tr ?? capitalize(m)).join(' ');
      const laFull = capitalize(`${headInfo.la} ${laMods}`.trim());
      const trFull = capitalize(`${trMods} ${headInfo.tr}`.trim());
      return {la: laFull, tr: trFull};
    }

    const laParts = tokens.map(t => TOKEN_MAP[t]?.la ?? t);
    const trParts = tokens.map(t => TOKEN_MAP[t]?.tr ?? t);
    return {
      la: capitalize(laParts.join(' ')),
      tr: capitalize(trParts.join(' ')),
    };
  }

  return {la: capitalize(en), tr: capitalize(en)};
}

function normalizeSearch(s) {
  return s
    .toLowerCase()
    .normalize('NFKD')
    .replace(/\p{M}/gu, '')
    .replace(/ı/g, 'i')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}

const entries = {};
let exactCount = 0;
let wikiCount = 0;
let composedCount = 0;

for (const c of atlas.concepts) {
  const en = c.name;
  const low = en.toLowerCase().trim();
  const w = wiki[c.id] ?? {};

  const composed = translatePhrase(en);
  let la = composed.la;
  let tr = composed.tr;

  if (EXACT_BASE.has(low)) {
    exactCount++;
  } else if (w.la && w.la.trim() && !w.la.includes(' of ')) {
    la = capitalize(w.la.trim());
    wikiCount++;
  } else {
    composedCount++;
  }

  // If wikidata has a clean Turkish term with Turkish characters and no English leftovers, prefer it when we didn't hit EXACT_BASE
  if (!EXACT_BASE.has(low) && w.tr && /[ğüşıöçĞÜŞİÖÇ]/.test(w.tr) && !/\b(of|the|branch|right|left|artery|vein|muscle|bone)\b/i.test(w.tr) && !/işlemi/i.test(w.tr)) {
    tr = capitalize(w.tr.trim());
  }

  const alt = new Set();
  if (w.trAlt) for (const a of w.trAlt) alt.add(a);
  if (w.la) alt.add(w.la);
  alt.add(en);
  alt.add(la);
  alt.add(tr);

  const search = [...new Set([tr, la, en, ...alt].map(normalizeSearch).filter(Boolean))];
  entries[c.id] = {en, la, tr, ...(alt.size ? {alt: [...alt]} : {}), search};
}

const catalog = {
  version: 1,
  generated: new Date().toISOString(),
  stats: {concepts: atlas.concepts.length, exactCount, wikiCount, composedCount},
  entries,
};

fs.writeFileSync(new URL('../public/models/terms.tr.json', import.meta.url), JSON.stringify(catalog));
console.log(`Wrote public/models/terms.tr.json · ${JSON.stringify(catalog.stats)}`);
